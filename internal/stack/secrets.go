package stack

import (
	"bufio"
	"crypto/rand"
	"encoding/hex"
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

const (
	SecretsFile   = ".env"
	AdminUser     = "ADMIN_USER"
	AdminPassword = "ADMIN_PASSWORD"
)

// Secrets is the stack's .env file. Values are generated once and then kept,
// so re-running the CLI never rotates a key an app already uses.
type Secrets struct {
	path string
	vals map[string]string
}

func LoadSecrets(dir string) (*Secrets, error) {
	s := &Secrets{path: filepath.Join(dir, SecretsFile), vals: map[string]string{}}
	f, err := os.Open(s.path)
	if errors.Is(err, os.ErrNotExist) {
		return s, nil
	}
	if err != nil {
		return nil, err
	}
	defer f.Close()
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		line := strings.TrimSpace(sc.Text())
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		if k, v, ok := strings.Cut(line, "="); ok {
			s.vals[strings.TrimSpace(k)] = strings.TrimSpace(v)
		}
	}
	return s, sc.Err()
}

func (s *Secrets) Get(name string) string { return s.vals[name] }

// Set stores a value an app handed out, such as an API key it created.
func (s *Secrets) Set(name, value string) { s.vals[name] = value }

// Ensure generates the secret if it does not exist yet.
func (s *Secrets) Ensure(name, kind string) error {
	if s.vals[name] != "" {
		return nil
	}
	switch kind {
	case "hex32":
		b := make([]byte, 16)
		if _, err := rand.Read(b); err != nil {
			return err
		}
		s.vals[name] = hex.EncodeToString(b)
	case "password":
		// Base32 text: no characters that need escaping in .env or config files.
		s.vals[name] = rand.Text()
	default:
		return fmt.Errorf("secret %s: unknown kind %q", name, kind)
	}
	return nil
}

// EnsureAdmin creates the shared admin login used for every app.
func (s *Secrets) EnsureAdmin() error {
	if s.vals[AdminUser] == "" {
		s.vals[AdminUser] = "admin"
	}
	return s.Ensure(AdminPassword, "password")
}

func (s *Secrets) Save() error {
	keys := make([]string, 0, len(s.vals))
	for k := range s.vals {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	var b strings.Builder
	b.WriteString("# Generated by stackwire. Keep this file private.\n")
	for _, k := range keys {
		fmt.Fprintf(&b, "%s=%s\n", k, s.vals[k])
	}
	return writeFile(s.path, []byte(b.String()), 0o600)
}
